import { normalize } from './text';

/** Фразы, которые Whisper «выдумывает» на тишине и шуме (след обучения на субтитрах). */
const HALLUCINATIONS = [
  'субтитры сделал', 'субтитры создавал', 'субтитры подогнал', 'редактор субтитров', 'корректор',
  'продолжение следует', 'спасибо за просмотр', 'спасибо за внимание', 'подписывайтесь на канал',
  'не забудьте подписаться', 'dimatorzok', 'до новых встреч', 'всем пока',
];

/**
 * Чистит вывод Whisper: убирает пометки вроде `[музыка]` и `(тишина)`, отбрасывает
 * типичные галлюцинации. Пустая строка означает «речи не было».
 */
export function cleanTranscript(raw: string): string {
  const text = raw
    .replace(/\[[^\]]*\]|\([^)]*\)|\*[^*]*\*/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  const n = normalize(text);
  if (!n) return '';
  if (HALLUCINATIONS.some((h) => n.includes(h))) return '';
  return text;
}
